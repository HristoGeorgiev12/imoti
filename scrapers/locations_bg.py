def resolve_neighborhood(city: str, neighborhood: str, location_raw: str, title: str, description: str) -> str:
    """Return normalized neighborhood, falling back to matching known neighborhoods in text."""
    nb = (neighborhood or "").strip()
    if nb:
        # Normalize "кв. Дивдядово" -> "Дивдядово"
        nb_clean = re.sub(r"^(?:кв\.?|ж\.?к\.?|м-т)\s+", "", nb, flags=re.I).strip()
        return nb_clean or nb

    known = CITY_NEIGHBORHOODS.get(city, [])
    if not known:
        return ""

    haystack = f"{location_raw} {title} {description}".lower()
    # Match longest names first (e.g. "Широк център" before "Център")
    for cand in sorted(known, key=len, reverse=True):
        if re.search(rf"(?<![а-яa-z]){re.escape(cand.lower())}(?![а-яa-z])", haystack):
            return cand
    return ""

