def _clean_place(name: str) -> str:
    s = (name or "").lower().strip()
    s = re.sub(r"^(?:гр\.?|град|с\.?|село|к\.?к\.?|курорт|м-т|местност|кв\.?|ж\.?к\.?)\s+", "", s)
    s = re.sub(r"\s+", " ", s).strip(" ,.-")
    return s


def resolve_municipality(city: str, neighborhood: str, location_raw: str, region: str) -> str:
    """Resolve Bulgarian municipality (община) from city/neighborhood/raw location."""
    table = SHUMEN_MUNICIPALITIES if region == "shumen" else VARNA_MUNICIPALITIES

    for candidate in (city, neighborhood, location_raw):
        cleaned = _clean_place(candidate)
        if not cleaned:
            continue
        if cleaned in table:
            return table[cleaned]
        # Try comma-separated parts
        for part in cleaned.split(","):
            p = _clean_place(part)
            if p in table:
                return table[p]

    # Check if any known settlement name appears in raw location
    raw_low = (location_raw or "").lower()
    for settlement, mun in table.items():
        if len(settlement) >= 4 and re.search(rf"\b{re.escape(settlement)}\b", raw_low):
            return mun

    return "Шумен" if region == "shumen" else "Варна"


